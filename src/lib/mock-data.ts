export function statusBadgeClass(status: StatusInscricao): string {
  switch (status) {
    case "Na fila": return "bg-amber-100 text-amber-800 border-amber-200";
    case "Chamado e aceito": return "bg-emerald-100 text-emerald-800 border-emerald-200";
    case "Chamado e não aceito": return "bg-rose-100 text-rose-800 border-rose-200";
    case "Já fez o retiro": return "bg-sky-100 text-sky-800 border-sky-200";
    case "Pediu para excluir da lista": return "bg-slate-100 text-slate-700 border-slate-200";
  }
}
// Status ativos: pessoa continua na fila.
const STATUS_NA_FILA: StatusInscricao[] = [
  "Na fila",
  "Chamado e aceito",
  "Chamado e não aceito",
];

export function calcularPosicoesFila(
  retirantes: { id: string; modalidade: string; status_inscricao: StatusInscricao; created_at: string }[],
): Map<string, number> {
  const porModalidade = new Map<string, typeof retirantes>();
  for (const r of retirantes) {
    if (!STATUS_NA_FILA.includes(r.status_inscricao)) continue;
    const arr = porModalidade.get(r.modalidade) ?? [];
    arr.push(r);
    porModalidade.set(r.modalidade, arr);
  }
  const posicoes = new Map<string, number>();
  for (const [, arr] of porModalidade) {
    arr.sort((a, b) => a.created_at.localeCompare(b.created_at));
    arr.forEach((r, i) => posicoes.set(r.id, i + 1));
  }
  return posicoes;
}
