export function calcularIdade(dataNascimentoIso: string, hoje: Date = new Date()): number | null {
  if (!dataNascimentoIso) return null;
  const nasc = new Date(dataNascimentoIso);
  if (Number.isNaN(nasc.getTime())) return null;
  let idade = hoje.getFullYear() - nasc.getFullYear();
  const m = hoje.getMonth() - nasc.getMonth();
  if (m < 0 || (m === 0 && hoje.getDate() < nasc.getDate())) idade--;
  return idade;
}

export function modalidadesPermitidasPorIdade(idade: number | null): Modalidade[] {
  if (idade === null) return [...MODALIDADES];
  return MODALIDADES.filter((m) => {
    const { min, max } = MODALIDADE_FAIXA_ETARIA[m];
    if (idade < min) return false;
    if (max !== null && idade > max) return false;
    return true;
  });
}

export function cpfJaInscritoNaModalidade(
  retirantes: { cpf: string; modalidade: string }[],
  cpf: string,
  modalidade: string,
): boolean {
  const norm = (v: string) => v.replace(/\D/g, "");
  const alvo = norm(cpf);
  if (!alvo) return false;
  return retirantes.some((r) => norm(r.cpf) === alvo && r.modalidade === modalidade);
}

export function validarCpf(cpf: string): boolean {
  const d = cpf.replace(/\D/g, "");
  if (d.length !== 11) return false;
  if (/^(\d)\1{10}$/.test(d)) return false;
  const calc = (base: string, factor: number) => {
    let sum = 0;
    for (let i = 0; i < base.length; i++) sum += parseInt(base[i], 10) * (factor - i);
    const r = (sum * 10) % 11;
    return r === 10 ? 0 : r;
  };
  const dv1 = calc(d.slice(0, 9), 10);
  const dv2 = calc(d.slice(0, 10), 11);
  return dv1 === parseInt(d[9], 10) && dv2 === parseInt(d[10], 10);
}



